"""Write the firmware header and leave the pickle for p_tremor_server.

emlearn emits an inline forest. The header is the on-device copy of the
pickle. Neither output is a diagnosis.
"""

from __future__ import annotations

import argparse
import pickle
from pathlib import Path

import emlearn

from ml.features import FEATURE_NAMES


def export_header(pickle_path: Path, header_path: Path) -> dict[str, object]:
    """Convert the saved sklearn model to firmware/band/src/model_params.h."""
    with pickle_path.open("rb") as handle:
        payload = pickle.load(handle)
    model = payload["model"]
    names = list(payload.get("feature_names", FEATURE_NAMES))
    if names != list(FEATURE_NAMES):
        raise ValueError("pickle feature order does not match ml.features.FEATURE_NAMES")
    converted = emlearn.convert(model, method="inline", dtype="float", leaf_bits=8)
    code = converted.save(name="tb_model")
    classes = [str(label) for label in model.classes_]
    if "tremor" not in classes:
        raise ValueError("model has no tremor class")
    listed = ", ".join(f'"{label}"' for label in classes)
    header = (
        "// Generated by ml/export_model.py. Do not edit by hand.\n"
        "// Inline tree from emlearn. The still rule gate runs before this model.\n"
        "// The score is not a diagnosis.\n"
        f"{code}\n"
        f"static const int TB_MODEL_N_FEATURES = {len(names)};\n"
        f"static const int TB_MODEL_N_CLASSES = {len(classes)};\n"
        f"static const int TB_MODEL_TREMOR_INDEX = {classes.index('tremor')};\n"
        f"static const char* const TB_MODEL_CLASSES[TB_MODEL_N_CLASSES] = {{{listed}}};\n"
    )
    header_path.parent.mkdir(parents=True, exist_ok=True)
    header_path.write_text(header, encoding="utf-8")
    return {"classes": classes, "kind": payload.get("kind"), "header": str(header_path)}


def main(argv: list[str] | None = None) -> int:
    """Export ml/model/tremor_model.pkl to the firmware header."""
    parser = argparse.ArgumentParser(description="Export the TremorBand model")
    parser.add_argument("--pickle", type=Path, default=Path("ml/model/tremor_model.pkl"))
    parser.add_argument("--header", type=Path, default=Path("firmware/band/src/model_params.h"))
    args = parser.parse_args(argv)
    written = export_header(args.pickle, args.header)
    print(f"wrote {written['header']} classes={','.join(written['classes'])} kind={written['kind']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
